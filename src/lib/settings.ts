const schemas = {
  discovery: discoverySettingsSchema,
  ai: aiSettingsSchema,
  threads: threadsSettingsSchema,
  profile: profileSettingsSchema,
  privacy: privacySettingsSchema,
} as const;

export type SettingKey = keyof typeof schemas;
export type SettingValue<K extends SettingKey> = z.infer<(typeof schemas)[K]>;

export async function getSetting<K extends SettingKey>(key: K): Promise<SettingValue<K>> {
  const row = await db.appSetting.findUnique({ where: { key } });
  const fallback = DEFAULT_SETTINGS[key] as SettingValue<K>;
  if (!row) return fallback;
  // Gabungkan dengan default agar field baru tidak membuat setting lama invalid.
  const merged = { ...fallback, ...(row.value as object) };
  const parsed = schemas[key].safeParse(merged);
  return parsed.success ? (parsed.data as SettingValue<K>) : fallback;
}

export async function setSetting<K extends SettingKey>(key: K, value: SettingValue<K>, actorId?: string) {
  const parsed = schemas[key].parse(value);
  await db.appSetting.upsert({
    where: { key },
    create: { key, value: parsed as object, updatedBy: actorId },
    update: { value: parsed as object, updatedBy: actorId },
  });
  return parsed as SettingValue<K>;
}

