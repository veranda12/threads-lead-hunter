export async function logActivity(
  tx: Prisma.TransactionClient | typeof db,
  entry: {
    leadId: string;
    type: Prisma.LeadActivityCreateInput["type"];
    message: string;
    actorId?: string | null;
    fromStatus?: LeadStatus;
    toStatus?: LeadStatus;
    metadata?: Prisma.InputJsonValue;
  },
) {
  await tx.leadActivity.create({
    data: {
      leadId: entry.leadId,
      type: entry.type,
      message: entry.message,
      actorId: entry.actorId ?? null,
      fromStatus: entry.fromStatus,
      toStatus: entry.toStatus,
      metadata: entry.metadata,
    },
  });
  await tx.lead.update({ where: { id: entry.leadId }, data: { lastActivityAt: new Date() } });
}

export type AnalyzeOutcome =
  | { status: "ANALYZED"; stage: "TRIAGE" | "FULL"; leadScore: number; inputTokens: number; outputTokens: number; draftsCreated: number }
  | { status: "SKIPPED_CACHED" }
  | { status: "BUDGET_EXCEEDED" | "NOT_CONFIGURED" | "FAILED" | "RETRY_LATER"; error: string };

type DraftCandidate = { body: string; issues: string[]; model: string };

/** Ubah hasil triage yang ditolak menjadi analisis lengkap bernilai rendah (tanpa memanggil model besar). */
function analysisFromTriage(t: TriageOutput, model: string): AnalysisOutput {
  return {
    intent: t.intent,
    category: "OTHER",
    isServiceRequest: false,
    confidence: t.confidence,
    leadScore: Math.min(t.relevance, 39),
    urgency: "UNKNOWN",
    projectComplexity: "UNKNOWN",
    budgetType: "NOT_MENTIONED",
    possibleBudget: null,
    budgetEvidence: null,
    estimatedService: null,
    qualificationReason: `Disaring classifier awal (${model}): ${t.reason}`.slice(0, 1000),
    recommendedApproach: "Tidak perlu ditindaklanjuti. Analisis ulang manual bila menurut Anda ini relevan.",
    redFlags: [],
    nextQuestion: null,
    promptInjectionDetected: false,
  };
}

/**
 * Analisis lead. Alur:
 *  1. Lewati bila konten + versi prompt sama dengan analisis terakhir (kecuali force).
 *  2. (Ollama + classifier awal diatur) triage dengan model kecil; yang jelas tidak relevan berhenti di sini.
 *  3. Satu panggilan model utama untuk klasifikasi + skor + tiga draft DM (JSON terstruktur).
 *  4. Guard deterministik; draft hanya disimpan untuk permintaan jasa dengan skor cukup.
 *     Draft yang melanggar aturan diperbaiki dengan satu panggilan khusus draft.
 */
export async function analyzeLead(
  leadId: string,
  opts: { runId?: string; force?: boolean; actorId?: string; withDrafts?: boolean } = {},
): Promise<AnalyzeOutcome> {
  const lead = await db.lead.findUniqueOrThrow({ where: { id: leadId }, include: { matchedKeyword: true } });
  const ai = await getSetting("ai");

  if (!opts.force) {
    const existing = await db.leadAnalysis.findFirst({
      where: { leadId, isCurrent: true, contentHash: lead.contentHash, promptVersion: ANALYSIS_PROMPT_VERSION },
    });
    if (existing) {
      if (lead.analysisStatus !== "ANALYZED") {
        await db.lead.update({ where: { id: leadId }, data: { analysisStatus: "ANALYZED", analysisError: null } });
      }
      return { status: "SKIPPED_CACHED" };
    }
  }

  const withDrafts = opts.withDrafts ?? ai.autoGenerateDrafts;
  const [catalog, profile, allowedPrices, recent] = await Promise.all([
    loadCatalog(),
    getSetting("profile"),
    allowedPriceValues(),
    db.messageDraftRevision.findMany({ orderBy: { createdAt: "desc" }, take: 15, select: { body: true } }),
  ]);
  const postInput = {
    text: lead.text,
    username: lead.authorUsername,
    postedAtIso: lead.postedAt?.toISOString() ?? null,
    matchedKeyword: lead.matchedKeyword?.phrase ?? null,
  };

  try {
    let stage: "TRIAGE" | "FULL" = "FULL";
    let output: AnalysisOutput;
    let drafts: CombinedOutput["drafts"] = [];
    let model: string;
    let usage = { inputTokens: 0, outputTokens: 0 };
    const triageNotes: string[] = [];

    // Tahap 1: classifier awal. Analisis ulang manual (force) selalu memakai model utama.
    const triageModel = ai.provider === "ollama" ? ai.ollamaTriageModel : "";
    let triageRejected = false;
    if (triageModel && !opts.force) {
      const t = await structuredCall({
        operation: "lead_triage",
        ai,
        ollamaModelOverride: triageModel,
        numCtx: 2048,
        system: buildTriageSystemPrompt(),
        user: buildTriageUserMessage(lead.text),
        schema: triageOutputSchema,
        maxTokens: 200,
        runId: opts.runId,
        leadId,
      });
      usage = { inputTokens: t.usage.inputTokens, outputTokens: t.usage.outputTokens };
      const relevance = clampScore(t.data.relevance);
      triageRejected = !triagePasses({ ...t.data, relevance }, ai.triageMinRelevance);
      triageNotes.push(`Triage ${t.model}: ${t.data.intent}, relevansi ${relevance}${triageRejected ? ", berhenti di triage" : ", diteruskan"}`);
      if (triageRejected) {
        stage = "TRIAGE";
        output = analysisFromTriage({ ...t.data, relevance }, t.model);
        model = t.model;
      }
    }

    // Tahap 2: satu panggilan model utama untuk analisis + draft.
    if (!triageRejected) {
      const bannedOpenings = [...new Set(recent.map((r) => openingOf(r.body)))].slice(0, 10);
      const full = withDrafts
        ? await structuredCall({
            operation: "lead_analysis_with_drafts",
            ai,
            numCtx: 6144,
            system: buildCombinedSystemPrompt(catalog, profile, ai.minLeadScoreForDrafts),
            user: buildCombinedUserMessage({ ...postInput, bannedOpenings }),
            schema: combinedOutputSchema,
            maxTokens: 2500,
            runId: opts.runId,
            leadId,
          })
        : await structuredCall({
            operation: "lead_analysis",
            ai,
            numCtx: 4096,
            system: buildAnalysisSystemPrompt(catalog),
            user: buildAnalysisUserMessage(postInput),
            schema: analysisOutputSchema,
            maxTokens: 1500,
            runId: opts.runId,
            leadId,
          });
      const { drafts: d, ...analysisPart } = full.data as CombinedOutput;
      output = analysisPart;
      drafts = d ?? [];
      model = full.model;
      usage = { inputTokens: usage.inputTokens + full.usage.inputTokens, outputTokens: usage.outputTokens + full.usage.outputTokens };
    }

    const guarded = applyAnalysisGuards(output!, { postText: lead.text, serviceSlugs: catalog.map((c) => c.slug) });
    guarded.guardNotes.unshift(...triageNotes);
    const wasAnalyzed = lead.analysisStatus === "ANALYZED";

    // Draft dari panggilan gabungan: hanya untuk permintaan jasa dengan skor cukup (keputusan guard, bukan model).
    const eligible = stage === "FULL" && withDrafts && guarded.isServiceRequest && guarded.leadScore >= ai.minLeadScoreForDrafts;
    const candidates = new Map<DraftToneId, DraftCandidate>();
    if (eligible) {
      for (const d of drafts) {
        if (candidates.has(d.tone)) continue;
        const body = sanitizeDraft(d.body);
        candidates.set(d.tone, { body, issues: validateDraft(body, { allowedPrices, experiences: profile.experiences, skills: profile.skills }), model: model! });
      }
    }

    await db.$transaction(async (tx) => {
      await tx.leadAnalysis.updateMany({ where: { leadId, isCurrent: true }, data: { isCurrent: false } });
      await tx.leadAnalysis.create({
        data: {
          leadId,
          modelVersion: model!,
          promptVersion: ANALYSIS_PROMPT_VERSION,
          stage,
          contentHash: lead.contentHash,
          intent: guarded.intent,
          category: guarded.category,
          isServiceRequest: guarded.isServiceRequest,
          confidence: guarded.confidence,
          leadScore: guarded.leadScore,
          priority: guarded.priority,
          urgency: guarded.urgency,
          projectComplexity: guarded.projectComplexity,
          budgetType: guarded.budgetType,
          possibleBudget: guarded.possibleBudget,
          budgetEvidence: guarded.budgetEvidence,
          estimatedService: guarded.estimatedService,
          qualificationReason: guarded.qualificationReason,
          recommendedApproach: guarded.recommendedApproach,
          redFlags: guarded.redFlags,
          nextQuestion: guarded.nextQuestion,
          guardNotes: guarded.guardNotes,
          raw: output! as unknown as Prisma.InputJsonValue,
          inputTokens: usage.inputTokens,
          outputTokens: usage.outputTokens,
        },
      });
      await tx.lead.update({
        where: { id: leadId },
        data: {
          analysisStatus: "ANALYZED",
          analysisError: null,
          intent: guarded.intent,
          category: guarded.category,
          leadScore: guarded.leadScore,
          priority: guarded.priority,
          estimatedService: guarded.estimatedService,
        },
      });
      if (!wasAnalyzed && lead.matchedKeywordId && guarded.leadScore >= 60) {
        await tx.searchKeyword.update({ where: { id: lead.matchedKeywordId }, data: { qualifiedLeads: { increment: 1 } } });
      }
      await logActivity(tx, {
        leadId,
        type: "ANALYZED",
        actorId: opts.actorId,
        message: `Dianalisis AI${stage === "TRIAGE" ? " (classifier awal)" : ""}: skor ${guarded.leadScore}, ${guarded.intent}`,
        metadata: { model: model!, stage, promptVersion: ANALYSIS_PROMPT_VERSION, guardNotes: guarded.guardNotes },
      });
    });

    let draftsCreated = 0;
    if (eligible) {
      const clean = new Map([...candidates].filter(([, c]) => c.issues.length === 0));
      if (clean.size) {
        await saveAiDrafts(leadId, clean, opts.actorId);
        draftsCreated += clean.size;
      }
      // Versi yang hilang atau melanggar aturan: satu panggilan perbaikan khusus draft.
      const repairTones = DRAFT_TONES.filter((t) => !clean.has(t));
      if (repairTones.length) {
        const seed = new Map([...candidates].filter(([t]) => repairTones.includes(t)));
        const repaired = await generateDrafts(leadId, { tones: repairTones, seed, runId: opts.runId, actorId: opts.actorId });
        if (repaired.ok) draftsCreated += repaired.tones.length;
      }
    }

    return { status: "ANALYZED", stage, leadScore: guarded.leadScore, inputTokens: usage.inputTokens, outputTokens: usage.outputTokens, draftsCreated };
  } catch (error) {
    const aiError = error instanceof AiError ? error : new AiError("API_ERROR", (error as Error)?.message ?? "Unknown");
    if (aiError.retryable) {
      // Tetap di antrian PENDING agar run berikutnya mencoba lagi; pesan error ditampilkan di UI.
      await db.lead.update({ where: { id: leadId }, data: { analysisStatus: "PENDING", analysisError: aiError.message.slice(0, 500) } });
      return { status: "RETRY_LATER", error: aiError.message };
    }
    const status = aiError.code === "BUDGET_EXCEEDED" ? "BUDGET_EXCEEDED" : aiError.code === "NOT_CONFIGURED" ? "NOT_CONFIGURED" : "FAILED";
    await db.lead.update({ where: { id: leadId }, data: { analysisStatus: status, analysisError: aiError.message.slice(0, 500) } });
    return { status, error: aiError.message };
  }
}

async function saveAiDrafts(leadId: string, byTone: Map<DraftToneId, DraftCandidate>, actorId?: string) {
  await db.$transaction(async (tx) => {
    for (const [tone, d] of byTone) {
      const draft = await tx.messageDraft.upsert({
        where: { leadId_tone: { leadId, tone } },
        create: { leadId, tone },
        update: {},
      });
      const last = await tx.messageDraftRevision.findFirst({ where: { draftId: draft.id }, orderBy: { revision: "desc" } });
      await tx.messageDraftRevision.create({
        data: {
          draftId: draft.id,
          revision: (last?.revision ?? 0) + 1,
          body: d.body,
          source: "AI",
          modelVersion: `${d.model}|${DRAFT_PROMPT_VERSION}`,
          issues: d.issues,
        },
      });
      await tx.messageDraft.update({ where: { id: draft.id }, data: { updatedAt: new Date() } });
    }
    await logActivity(tx, {
      leadId,
      type: "DRAFT_GENERATED",
      actorId,
      message: `Draft DM dibuat: ${[...byTone.keys()].join(", ")}`,
    });
  });
}

export type DraftOutcome = { ok: true; tones: DraftToneId[]; issues: Record<string, string[]> } | { ok: false; error: string; code?: string };

export async function generateDrafts(
  leadId: string,
  opts: {
    tones?: DraftToneId[];
    runId?: string;
    actorId?: string;
    /** Draft yang sudah dibuat panggilan gabungan; hanya versi bermasalah yang diperbaiki. */
    seed?: Map<DraftToneId, DraftCandidate>;
  } = {},
): Promise<DraftOutcome> {
  const tones = opts.tones?.length ? opts.tones : [...DRAFT_TONES];
  const lead = await db.lead.findUniqueOrThrow({
    where: { id: leadId },
    include: { analyses: { where: { isCurrent: true }, take: 1 } },
  });
  const analysis = lead.analyses[0];
  if (!analysis) return { ok: false, error: "Lead belum dianalisis" };
  if (!analysis.isServiceRequest) return { ok: false, error: "Lead tidak terindikasi sebagai permintaan jasa, draft tidak dibuat" };

  const [ai, profile, catalog, allowedPrices, recent] = await Promise.all([
    getSetting("ai"),
    getSetting("profile"),
    loadCatalog(),
    allowedPriceValues(),
    db.messageDraftRevision.findMany({ orderBy: { createdAt: "desc" }, take: 15, select: { body: true } }),
  ]);
  const service = catalog.find((c) => c.slug === analysis.estimatedService) ?? null;
  const bannedOpenings = [...new Set(recent.map((r) => openingOf(r.body)))].slice(0, 10);
  const system = buildDraftSystemPrompt(profile);
  const summary = `${analysis.qualificationReason} Pendekatan: ${analysis.recommendedApproach}`;

  const callOnce = async (forTones: DraftToneId[], feedback?: string[]) => {
    const result = await structuredCall({
      operation: "dm_drafts",
      ai,
      system,
      user: buildDraftUserMessage({
        postText: lead.text,
        username: lead.authorUsername,
        analysisSummary: summary,
        serviceName: service?.name ?? null,
        priceText: service?.priced ? service.priceText : UNPRICED_PHRASE,
        bannedOpenings,
        tones: forTones,
        feedback,
      }),
      schema: draftsOutputSchema,
      maxTokens: 3000,
      runId: opts.runId,
      leadId,
    });
    return { model: result.model, drafts: result.data.drafts };
  };

  try {
    const byTone = new Map<DraftToneId, DraftCandidate>(opts.seed ?? []);
    if (!opts.seed) {
      const first = await callOnce(tones);
      for (const d of first.drafts) {
        if (!tones.includes(d.tone) || byTone.has(d.tone)) continue;
        const body = sanitizeDraft(d.body);
        byTone.set(d.tone, { body, issues: validateDraft(body, { allowedPrices, experiences: profile.experiences, skills: profile.skills }), model: first.model });
      }
    }
    // Satu kali perbaikan untuk versi yang hilang atau melanggar aturan.
    const retryTones = tones.filter((t) => !byTone.has(t) || byTone.get(t)!.issues.length > 0);
    if (retryTones.length > 0) {
      const feedback = retryTones.flatMap((t) => (byTone.get(t)?.issues ?? ["Versi ini belum dibuat"]).map((i) => `${t}: ${i}`));
      try {
        const second = await callOnce(retryTones, feedback);
        for (const d of second.drafts) {
          if (!retryTones.includes(d.tone)) continue;
          const body = sanitizeDraft(d.body);
          const issues = validateDraft(body, { allowedPrices, experiences: profile.experiences, skills: profile.skills });
          const prev = byTone.get(d.tone);
          if (!prev || issues.length <= prev.issues.length) byTone.set(d.tone, { body, issues, model: second.model });
        }
      } catch (error) {
        if (byTone.size === 0) throw error;
      }
    }
    if (byTone.size === 0) return { ok: false, error: "Model tidak menghasilkan draft" };

    await saveAiDrafts(leadId, byTone, opts.actorId);
    return { ok: true, tones: [...byTone.keys()], issues: Object.fromEntries([...byTone].map(([t, d]) => [t, d.issues])) };
  } catch (error) {
    if (error instanceof AiError) return { ok: false, error: error.message, code: error.code };
    throw error;
  }
}

export async function saveManualDraft(draftId: string, body: string, actorId: string) {
  const clean = body.trim();
  if (clean.length < 10 || clean.length > 2000) throw new Error("Panjang draft harus 10 sampai 2000 karakter");
  const allowedPrices = await allowedPriceValues();
  const issues = validateDraft(clean, { allowedPrices });
  return db.$transaction(async (tx) => {
    const draft = await tx.messageDraft.findUniqueOrThrow({ where: { id: draftId } });
    const last = await tx.messageDraftRevision.findFirst({ where: { draftId }, orderBy: { revision: "desc" } });
    if (last?.body === clean) return { issues: last.issues };
    await tx.messageDraftRevision.create({
      data: { draftId, revision: (last?.revision ?? 0) + 1, body: clean, source: "MANUAL", issues },
    });
    await tx.messageDraft.update({ where: { id: draftId }, data: { updatedAt: new Date() } });
    await logActivity(tx, { leadId: draft.leadId, type: "DRAFT_EDITED", actorId, message: `Draft ${draft.tone} diedit manual` });
    return { issues };
  });
}

export async function changeLeadStatus(leadId: string, to: LeadStatus, actorId: string, note?: string) {
  return db.$transaction(async (tx) => {
    const lead = await tx.lead.findUniqueOrThrow({ where: { id: leadId } });
    const from = lead.status as LeadStatus;
    assertTransition(from, to);
    const now = new Date();
    await tx.lead.update({
      where: { id: leadId },
      data: {
        status: to,
        contactedAt: to === "CONTACTED" && !lead.contactedAt ? now : undefined,
      },
    });
    await logActivity(tx, {
      leadId,
      type: to === "CONTACTED" ? "CONTACTED" : "STATUS_CHANGED",
      actorId,
      fromStatus: from,
      toStatus: to,
      message: `Status: ${STATUS_LABELS[from]} ke ${STATUS_LABELS[to]}${note ? `. ${note}` : ""}`,
    });
    return { from, to };
  });
}
