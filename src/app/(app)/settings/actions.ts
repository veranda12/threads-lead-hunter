export type SettingsState = { ok?: boolean; message?: string } | undefined;

const int = (v: FormDataEntryValue | null) => (typeof v === "string" && v.trim() !== "" ? Number(v) : NaN);
const bool = (v: FormDataEntryValue | null) => v === "on" || v === "true";
const nullableInt = (v: FormDataEntryValue | null) => (typeof v === "string" && v.trim() !== "" ? Number(v) : null);
const lines = (v: FormDataEntryValue | null) =>
  typeof v === "string"
    ? v
        .split("\n")
        .map((s) => s.trim())
        .filter(Boolean)
    : [];

function fail(error: z.ZodError): SettingsState {
  const issue = error.issues[0];
  return { ok: false, message: `${issue.path.join(".") || "Input"}: ${issue.message}` };
}

export async function saveDiscoveryAction(_p: SettingsState, fd: FormData): Promise<SettingsState> {
  const user = await assertUser();
  try {
    const value = await setSetting(
      "discovery",
      {
        enabled: bool(fd.get("enabled")),
        maxPostsPerRun: int(fd.get("maxPostsPerRun")),
        maxKeywordsPerRun: int(fd.get("maxKeywordsPerRun")),
        maxPagesPerKeyword: int(fd.get("maxPagesPerKeyword")),
        resultsPerPage: int(fd.get("resultsPerPage")),
        minIntervalMinutes: int(fd.get("minIntervalMinutes")),
        runTimeoutSeconds: int(fd.get("runTimeoutSeconds")),
      },
      user.id,
    );
    await audit({ action: "settings.discovery_updated", actorId: user.id, metadata: value });
  } catch (e) {
    if (e instanceof z.ZodError) return fail(e);
    throw e;
  }
  refresh();
  return { ok: true, message: "Pengaturan scheduler disimpan." };
}

