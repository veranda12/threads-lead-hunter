export type TestSearchState =
  | {
      ok: boolean;
      message: string;
      keyword?: string;
      results?: { username: string | null; text: string; timestamp: string | null; permalink: string | null }[];
    }
  | undefined;

/**
 * Panggilan uji ke Threads Keyword Search dengan token yang tersimpan. Hasilnya hanya ditampilkan,
 * tidak disimpan sebagai lead. Sebelum threads_keyword_search disetujui, API hanya mengembalikan
 * postingan milik akun yang terhubung.
 */
export async function testKeywordSearchAction(_p: TestSearchState, fd: FormData): Promise<TestSearchState> {
  const user = await assertUser();
  const limit = await consumeRateLimit(`threads:test:${user.id}`, 10, 3600);
  if (!limit.allowed) return { ok: false, message: "Uji pencarian dibatasi 10 kali per jam." };
  const parsed = z.string().trim().min(2, "Keyword minimal 2 karakter").max(100).safeParse(fd.get("keyword"));
  if (!parsed.success) return { ok: false, message: parsed.error.issues[0].message };

  const { accessToken, tokenError } = await loadThreadsState();
  if (!accessToken) return { ok: false, message: tokenError ?? "Akun Threads belum dihubungkan." };

  const now = new Date();
  const started = Date.now();
  try {
    const page = await keywordSearch(accessToken, {
      keyword: parsed.data,
      since: new Date(now.getTime() - 30 * 86_400_000),
      until: now,
      limit: 10,
    });
    await db.apiUsageLog.create({
      data: { provider: "THREADS", operation: "keyword_search_test", statusCode: 200, success: true, quotaUnits: page.quotaUnits, durationMs: Date.now() - started },
    });
    await db.integrationAccount.updateMany({ where: { provider: "OFFICIAL_THREADS" }, data: { lastCheckedAt: now } });
    await audit({ action: "threads.keyword_search_test", actorId: user.id, metadata: { keyword: parsed.data, results: page.posts.length } });
    return {
      ok: true,
      keyword: parsed.data,
      message: `Berhasil: Threads API mengembalikan ${page.posts.length} postingan untuk "${parsed.data}" (30 hari terakhir).`,
      results: page.posts.map((p) => ({
        username: p.username,
        text: (p.text ?? "").slice(0, 280),
        timestamp: typeof p.timestamp === "string" ? p.timestamp : null,
        permalink: p.permalink,
      })),
    };
  } catch (error) {
    const pe = error instanceof ProviderError ? error : new ProviderError("PROVIDER_ERROR", (error as Error).message);
    await db.apiUsageLog.create({
      data: { provider: "THREADS", operation: "keyword_search_test", statusCode: pe.options.httpStatus ?? null, success: false, error: pe.message.slice(0, 500), durationMs: Date.now() - started },
    });
    await recordProviderError(pe, now);
    return { ok: false, keyword: parsed.data, message: `${PROVIDER_STATUS_LABELS[statusFromErrorCode(pe.code)]}: ${pe.message}` };
  }
}
