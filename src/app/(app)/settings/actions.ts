export async function savePrivacyAction(_p: SettingsState, fd: FormData): Promise<SettingsState> {
  const user = await assertUser();
  try {
    const email = String(fd.get("contactEmail") ?? "").trim();
    if (email && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) return { ok: false, message: "Format email kontak tidak valid" };
    const date = String(fd.get("effectiveDate") ?? "").trim();
    if (date && !/^\d{4}-\d{2}-\d{2}$/.test(date)) return { ok: false, message: "Tanggal berlaku harus format YYYY-MM-DD" };
    const value = await setSetting(
      "privacy",
      {
        controllerName: String(fd.get("controllerName") ?? "").trim(),
        contactEmail: email,
        contactAddress: String(fd.get("contactAddress") ?? "").trim(),
        effectiveDate: date,
        retentionUnqualifiedDays: nullableInt(fd.get("retentionUnqualifiedDays")),
        retentionRawPayloadDays: nullableInt(fd.get("retentionRawPayloadDays")),
        retentionClosedLeadDays: nullableInt(fd.get("retentionClosedLeadDays")),
        deletionResponseDays: nullableInt(fd.get("deletionResponseDays")),
      },
      user.id,
    );
    await audit({ action: "settings.privacy_updated", actorId: user.id, metadata: value });
  } catch (e) {
    if (e instanceof z.ZodError) return fail(e);
    throw e;
  }
  refresh();
  return { ok: true, message: "Pengaturan privasi disimpan. Halaman /privacy-policy langsung memakai nilai ini." };
}

export async function changePasswordAction(_p: SettingsState, fd: FormData): Promise<SettingsState> {
  const user = await assertUser();
  const limit = await consumeRateLimit(`password:${user.id}`, 5, 900);
  if (!limit.allowed) return { ok: false, message: "Terlalu banyak percobaan. Coba lagi nanti." };
  const current = String(fd.get("current") ?? "");
  const next = String(fd.get("next") ?? "");
  const confirm = String(fd.get("confirm") ?? "");
  if (next.length < 12) return { ok: false, message: "Password baru minimal 12 karakter." };
  if (next !== confirm) return { ok: false, message: "Konfirmasi password tidak sama." };
  const row = await db.user.findUniqueOrThrow({ where: { id: user.id } });
  if (!(await verifyPassword(current, row.passwordHash))) return { ok: false, message: "Password saat ini salah." };
  await db.user.update({ where: { id: user.id }, data: { passwordHash: await hashPassword(next) } });
  const revoked = await revokeOtherSessions(user.id, user.sessionId);
  await audit({ action: "auth.password_changed", actorId: user.id, metadata: { revokedSessions: revoked } });
  return { ok: true, message: `Password diganti. ${revoked} sesi lain dikeluarkan.` };
}

export async function revokeSessionsAction() {
  const user = await assertUser();
  const revoked = await revokeOtherSessions(user.id, user.sessionId);
  await audit({ action: "auth.sessions_revoked", actorId: user.id, metadata: { revoked } });
  refresh();
}

