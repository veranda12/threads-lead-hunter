export async function saveThreadsAction(_p: SettingsState, fd: FormData): Promise<SettingsState> {
  const user = await assertUser();
  try {
    const before = await getSetting("threads");
    const value = await setSetting(
      "threads",
      { keywordSearchApproved: bool(fd.get("keywordSearchApproved")), dailyQueryBudget: int(fd.get("dailyQueryBudget")) },
      user.id,
    );
    if (before.keywordSearchApproved !== value.keywordSearchApproved && value.keywordSearchApproved) {
      // Reset status izin agar pencarian berikutnya mencoba lagi dengan izin baru.
      await db.integrationAccount.updateMany({ where: { provider: "OFFICIAL_THREADS", status: "PERMISSION_REQUIRED" }, data: { status: "CONNECTED", statusMessage: null } });
    }
    await audit({ action: "settings.threads_updated", actorId: user.id, metadata: value });
  } catch (e) {
    if (e instanceof z.ZodError) return fail(e);
    throw e;
  }
  refresh();
  return { ok: true, message: "Pengaturan Threads disimpan." };
}

